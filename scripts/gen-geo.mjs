// Builds src/data/geo.js from the bundled PSGC dataset.
//
//   npm run gen:geo
//
// Province codes come from the live PSA PSGC API (one request) and are cached in
// scripts/psgc-provinces.json so regeneration works offline after the first run.
//
// The hierarchy is derived from the barangay table rather than joined against the
// municipality table: the two use different name spellings for the same place
// ("City Of Vigan Capital" vs "Vigan City"), which drops 352 large cities when
// joined. The municipality table is still consulted, but only to flag isCity.
//
// Output shape (short keys keep the bundle small):
//   PH_GEO = [{ p: "Province", c: [{ n: "City", t: 1, b: ["Barangay", ...] }] }]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "node_modules", "psgc", "dist", "data");
const cacheFile = path.join(root, "scripts", "psgc-provinces.json");

const read = (name) => JSON.parse(fs.readFileSync(path.join(dataDir, `${name}.json`), "utf8"));

// A barangay code is <province(4)><citymun(3)><barangay(3)>, so the first four
// digits identify the province without relying on names.
//
// The island group is carried through to the output so shipping zones can be
// derived from the address instead of hardcoded per province.
async function provinceCodeCache() {
  if (fs.existsSync(cacheFile)) return JSON.parse(fs.readFileSync(cacheFile, "utf8"));
  process.stdout.write("Fetching PSGC province codes... ");
  const res = await fetch("https://psgc.gitlab.io/api/provinces/");
  if (!res.ok) throw new Error(`PSGC API returned ${res.status}`);
  const rows = await res.json();
  const map = {};
  for (const r of rows) map[r.code.slice(0, 4)] = { name: r.name, island: r.islandGroupCode };
  fs.writeFileSync(cacheFile, JSON.stringify(map, null, 2), "utf8");
  console.log(`${Object.keys(map).length} provinces`);
  return map;
}

// "(Pob.)" is a PSGC settlement-type marker, noise in a dropdown.
const clean = (s) => s.replace(/\s*\((?:Pob\.)\)\s*$/i, "").trim();

// PSGC spells some cities verbosely in the barangay table. Only the unambiguous
// wrappers are unwrapped; anything else is left alone so names never collide.
const niceCity = (s) => {
  const stripped = clean(s)
    .replace(/^City Of /i, "")
    .replace(/\s*-\s*.*$/, "")
    .trim();
  // "Capital" marks the seat of government; render it as "City" unless the
  // stripped name already says so ("City Of Batangas City Capital").
  if (/\s+Capital$/i.test(stripped)) {
    const base = stripped.replace(/\s+Capital$/i, "").trim();
    return /\bCity$/i.test(base) ? base : `${base} City`;
  }
  return stripped;
};

const municipalities = read("municipalities");
const barangays = read("barangays");
const codeToProvince = await provinceCodeCache();

const isCity = new Set();
for (const m of municipalities) {
  if (!m.city) continue;
  // Register both spellings so "Lipa" in the table matches a "Lipa City" group.
  isCity.add(`${m.province} ${clean(m.name)}`);
  isCity.add(`${m.province} ${niceCity(m.name)}`);
}
const looksLikeCity = (province, name) =>
  isCity.has(`${province} ${name}`) || isCity.has(`${province} ${name.replace(/\s+City$/i, "")}`);

// Fallback for the handful of barangays whose prefix is not in the code map:
// resolve the province by looking the city up in the municipality table.
const cityToProvince = new Map(municipalities.map((m) => [`${clean(m.name)}`, m.province]));

const provinceOf = (code) => codeToProvince[String(code).slice(0, 4)];
const islandOf = (province) => codeToProvinceIsland.get(province) ?? "luzon";
const codeToProvinceIsland = new Map(
  Object.values(codeToProvince).map((v) => [v.name, v.island])
);

const byProvince = new Map();
let unmatched = 0;
for (const b of barangays) {
  const hit = provinceOf(b.code);
  let province = hit?.name;
  if (!province) {
    province = cityToProvince.get(clean(b.citymun));
    if (!province) {
      unmatched++;
      continue;
    }
  }
  if (!byProvince.has(province)) byProvince.set(province, new Map());
  const cities = byProvince.get(province);
  const name = niceCity(b.citymun);
  if (!cities.has(name)) cities.set(name, []);
  cities.get(name).push(clean(b.name));
}

const ISLAND_CODE = { luzon: "L", visayas: "V", mindanao: "M" };

const PH_GEO = [...byProvince.entries()]
  .map(([p, cities]) => ({
    p,
    i: ISLAND_CODE[islandOf(p)] ?? "L",
    c: [...cities.entries()]
      .map(([n, list]) => ({ n, t: looksLikeCity(p, n) ? 1 : 0, b: [...new Set(list)].sort((a, z) => a.localeCompare(z, "en")) }))
      .sort((a, z) => a.n.localeCompare(z.n, "en")),
  }))
  .sort((a, z) => a.p.localeCompare(z.p, "en"));

const out = `// AUTO-GENERATED by scripts/gen-geo.mjs - do not edit by hand.
// Source: PSA Philippine Standard Geographic Code (PSGC), via the \`psgc\` package.
// Regenerate with: npm run gen:geo
//
// p = province, i = island group (L Luzon, V Visayas, M Mindanao),
// c = city or municipality, n = name, t = 1 when it is a city,
// b = barangays (PSGC "(Pob.)" suffixes stripped).

export const PH_GEO = ${JSON.stringify(PH_GEO)};
`;

const dest = path.join(root, "src", "data", "geo.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out, "utf8");

const total = PH_GEO.reduce((n, p) => n + p.c.reduce((m, c) => m + c.b.length, 0), 0);
console.log(`Wrote ${path.relative(root, dest)}`);
console.log(`  ${PH_GEO.length} provinces, ${PH_GEO.reduce((n, p) => n + p.c.length, 0)} cities, ${total} barangays`);
console.log(`  ${total} of ${barangays.length} source barangays placed${unmatched ? `, ${unmatched} dropped` : ""}`);
console.log(`  ${(out.length / 1024).toFixed(0)} KB raw`);